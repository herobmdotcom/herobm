const fs = require('fs');
const path = require('path');
const MarkdownIt = require('markdown-it');

const md = new MarkdownIt({ html: true });

function generate() {
  const mdPath = path.join(__dirname, '../../../docs/developers/webhooks.md');
  const outDir = path.join(__dirname, '../lib/generated');
  const outFile = path.join(outDir, 'webhooks-content.ts');

  if (!fs.existsSync(mdPath)) {
    console.error('Could not find webhooks.md at ' + mdPath);
    process.exit(1);
  }

  const markdownContent = fs.readFileSync(mdPath, 'utf-8');
  
  // Render markdown to HTML
  const htmlContent = md.render(markdownContent);

  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const tsContent = `// Auto-generated by scripts/generate-webhooks-content.js
// Do not edit directly

export const webhooksHtmlContent = ${JSON.stringify(htmlContent)};
`;

  fs.writeFileSync(outFile, tsContent);
  console.log('Generated webhooks-content.ts from webhooks.md');
}

generate();
